drop policy if exists "Public can create volunteers" on public.volunteers;
create policy "Public can create volunteers" on public.volunteers for insert with check (true);

drop policy if exists "Public can read admin setting values" on public.admin_settings;
create policy "Public can read admin setting values" on public.admin_settings for select using (true);

