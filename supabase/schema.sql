create policy "Public can read active sections" on public.content_sections for select using (is_active = true);

drop policy if exists "Public can read published content" on public.content_items;
create policy "Public can read published content" on public.content_items for select using (is_published = true);

drop policy if exists "Public can read published vlogs" on public.vlog_reviews;
create policy "Public can read published vlogs" on public.vlog_reviews for select using (is_published = true);

drop policy if exists "Public can read vlog locations" on public.vlog_locations;
create policy "Public can read vlog locations" on public.vlog_locations for select using (true);

